create table if not exists public.agents (
  id bigint generated by default as identity primary key,
  profile_image_url text,
  first_name text not null,
  last_name text not null,
  role_title text not null default 'Realtor',
  license_number text,
  email text not null default '',
  phone text,
  street text,
  city text,
  state text,
  zip text,
  calendar_color text not null default '#837a6d',
  commission_split numeric(5,2) not null default 70,
  compensation_option text not null default 'split' check (compensation_option in ('split', 'flat')),
  flat_transaction_fee numeric(12,2) not null default 0,
  contract_effective_date date,
  contract_status text not null default 'Draft',
  license_file_name text,
  contract_file_name text,
  other_file_name text,
  license_expires_on date,
  archived boolean not null default false,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.agents add column if not exists role_title text not null default 'Realtor';
alter table public.agents add column if not exists license_number text;
alter table public.agents add column if not exists compensation_option text not null default 'split';
alter table public.agents add column if not exists flat_transaction_fee numeric(12,2) not null default 0;
alter table public.agents add column if not exists contract_effective_date date;
alter table public.agents add column if not exists contract_status text not null default 'Draft';
alter table public.agents add column if not exists contract_file_name text;
alter table public.agents add column if not exists other_file_name text;
alter table public.agents add column if not exists details jsonb not null default '{}'::jsonb;
alter table public.agents alter column email drop not null;
alter table public.agents drop constraint if exists agents_email_key;
create unique index if not exists agents_email_unique on public.agents (lower(email)) where length(btrim(email)) > 0;

alter table public.agents enable row level security;
grant select, insert, update, delete on public.agents to authenticated;
grant usage, select on sequence public.agents_id_seq to authenticated;

drop policy if exists "prototype read agents" on public.agents;
drop policy if exists "prototype write agents" on public.agents;
drop policy if exists "authenticated users read agents" on public.agents;
create policy "authenticated users read agents"
on public.agents for select to authenticated
using (
  exists (
    select 1 from public.app_users
    where app_users.auth_user_id = (select auth.uid())
      and app_users.status = 'Active'
  )
);

drop policy if exists "brokers manage agents" on public.agents;
create policy "brokers manage agents"
on public.agents for all to authenticated
using (
  exists (
    select 1 from public.app_users
    where app_users.auth_user_id = (select auth.uid())
      and app_users.status = 'Active'
      and app_users.role in ('Broker', 'Admin')
  )
)
with check (
  exists (
    select 1 from public.app_users
    where app_users.auth_user_id = (select auth.uid())
      and app_users.status = 'Active'
      and app_users.role in ('Broker', 'Admin')
  )
);
